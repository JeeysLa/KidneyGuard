@Injectable({
  providedIn: 'root'
})
export class TranslationService {
  private currentLangSubject = new BehaviorSubject<LanguageCode>(this.loadLang());
  currentLang$ = this.currentLangSubject.asObservable();

  constructor() { }

  private loadLang(): LanguageCode {
    const saved = localStorage.getItem('kidney_guard_lang') as LanguageCode;
    return saved === 'id' || saved === 'en' ? saved : 'id';
  }

  setLanguage(lang: LanguageCode) {
    localStorage.setItem('kidney_guard_lang', lang);
    this.currentLangSubject.next(lang);
  }

  get activeLanguage(): LanguageCode {
    return this.currentLangSubject.value;
  }

  translate(key: keyof typeof EN_TRANS): string {
    const lang = this.activeLanguage;
    const dictionary = lang === 'en' ? EN_TRANS : ID_TRANS;
    return dictionary[key] || EN_TRANS[key] || String(key);
  }
}
